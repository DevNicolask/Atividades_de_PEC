"""Um dragão come exatamente meia ovelha por dia. Pergunte ao usuário por quantos dias o dragão está solto. Calcule 
quantas ovelhas ele já comeu nesse tempo! """

dias = float(input("Quantos dias se passaram? "))
quantidade_de_ovelhas = int(0.5 * dias)

print(f'A quantidade de ovelhsa que o dragão comeu foi de: {quantidade_de_ovelhas} ovelhas.')
